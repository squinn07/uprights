/* Bundles the .fbx files in assets/mixamo/ into assets/mixamo-pack.js.

   Browsers will not let a page opened straight from disk read other files, so the
   Mixamo downloads are embedded in a script the page can load. Re-run this every
   time you add or replace a file:

       node tools/pack-mixamo.js        (or double-click tools/pack-mixamo.bat)
*/
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'assets', 'mixamo');
const out = path.join(__dirname, '..', 'assets', 'mixamo-pack.js');
const KNOWN = ['character', 'idle', 'kick', 'kneel', 'snap', 'celebrate'];

const files = {};
for (const f of fs.existsSync(dir) ? fs.readdirSync(dir) : []) {
  if (!/\.fbx$/i.test(f)) continue;
  const name = path.basename(f, path.extname(f)).toLowerCase();
  const buf = fs.readFileSync(path.join(dir, f));
  files[name] = buf.toString('base64');
  const note = KNOWN.includes(name) ? '' : '   (name not used by the game - see README.txt)';
  console.log(`  ${f.padEnd(22)} ${(buf.length / 1048576).toFixed(1)} MB${note}`);
}

let config = {};
const cfgPath = path.join(dir, 'config.json');
if (fs.existsSync(cfgPath)) {
  try { config = JSON.parse(fs.readFileSync(cfgPath, 'utf8')); } catch (e) { console.warn('config.json is not valid JSON, ignoring it.'); }
}

if (!Object.keys(files).length) {
  fs.writeFileSync(out, '// No Mixamo files packed yet - the game uses its built-in players.\nwindow.MIXAMO_PACK = null;\n');
  console.log('No .fbx files found in assets/mixamo/. The game will use its built-in players.');
} else {
  fs.writeFileSync(out, '// Generated by tools/pack-mixamo.js - do not edit.\nwindow.MIXAMO_PACK = ' + JSON.stringify({ files, config }) + ';\n');
  console.log(`\nWrote assets/mixamo-pack.js (${(fs.statSync(out).size / 1048576).toFixed(1)} MB).`);
  if (!files.character) console.log('WARNING: character.fbx is missing, so nothing will be used.');
  const roles = { kicker: ['idle', 'kick'], holder: ['kneel'], 'long snapper': ['snap'] };
  for (const [role, need] of Object.entries(roles)) {
    const missing = need.filter(n => !files[n]);
    console.log(`  ${role.padEnd(13)} ${files.character && !missing.length ? 'Mixamo' : 'built-in (missing ' + (files.character ? missing.join(', ') : 'character') + ')'}`);
  }
}
